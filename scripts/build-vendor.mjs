import { build, version as esbuildVersion } from 'esbuild';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { isBuiltin } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import assert from 'node:assert/strict';

const root = fileURLToPath(new URL('../', import.meta.url));
const check = process.argv.includes('--check');
const result = await build({
  absWorkingDir: root,
  entryPoints: ['scripts/qr-entry.cjs'],
  outfile: 'vendor/qrcode.cjs',
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  charset: 'utf8',
  legalComments: 'inline',
  banner: { js: '// Generated by npm run build:vendor. Third-party licenses: licenses.txt.' },
  write: false,
  metafile: true,
  logLevel: 'silent',
});
const external = Object.values(result.metafile.outputs).flatMap(output => output.imports)
  .filter(item => item.external).map(item => item.path);
assert.ok(external.every(isBuiltin), `Unexpected external dependencies: ${external}`);
const inputs = Object.keys(result.metafile.inputs).sort();
const names = [...new Set(inputs.flatMap(input => {
  const match = /^node_modules\/((?:@[^/]+\/)?[^/]+)\//.exec(input);
  return match ? [match[1]] : [];
}))].sort();
assert.deepEqual(names, ['dijkstrajs', 'pngjs', 'qrcode']);
const packages = [];
const licenses = [];
for (const name of names) {
  const directory = path.join(root, 'node_modules', name);
  const manifest = JSON.parse(await readFile(path.join(directory, 'package.json'), 'utf8'));
  let license;
  for (const filename of ['LICENSE', 'LICENSE.txt', 'LICENSE.md', 'license']) {
    try { license = await readFile(path.join(directory, filename), 'utf8'); break; }
    catch (error) { if (error.code !== 'ENOENT') throw error; }
  }
  assert.ok(license?.trim(), `Missing license: ${name}`);
  packages.push({ name, version: manifest.version, license: manifest.license });
  licenses.push(`===== ${name}@${manifest.version} (${manifest.license}) =====\n\n${license.trim()}\n`);
}
const code = result.outputFiles[0].contents;
const artifacts = new Map([
  ['qrcode.cjs', code],
  ['licenses.txt', licenses.join('\n')],
  ['manifest.json', `${JSON.stringify({
    generator: `esbuild@${esbuildVersion}`,
    entry: 'scripts/qr-entry.cjs',
    sha256: createHash('sha256').update(code).digest('hex'),
    packages, inputs,
    external: [...new Set(external)].sort(),
  }, null, 2)}\n`],
]);
if (!check) await mkdir(path.join(root, 'vendor'), { recursive: true });
for (const [filename, content] of artifacts) {
  const target = path.join(root, 'vendor', filename);
  if (check) assert.deepEqual(await readFile(target), Buffer.from(content), `Stale artifact: vendor/${filename}; run npm run build:vendor`);
  else await writeFile(target, content);
}
console.log(`${check ? 'Verified' : 'Built'} reproducible QR bundle: ${code.byteLength} bytes, ${names.length} bundled packages, Node built-ins only.`);
